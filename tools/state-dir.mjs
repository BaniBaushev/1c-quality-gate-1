/**
 * Каталог состояния гейта — единственное место, где он определяется.
 *
 * Умолчание `.claude/.state` — историческое, менять его ломающе (см. docs/RELEASING.md:
 * расположение состояния — MAJOR-изменение). Переменная `QG_STATE_DIR` даёт второму
 * харнессу (OpenCode) свой каталог, не трогая существующие установки: плагин OpenCode
 * экспортирует её в окружение процесса, и все инструменты, запущенные агентом из
 * оболочки, наследуют то же значение — взвод и снятие попадают в один маркер.
 *
 * Значение — относительный путь от корня проекта, например `.opencode/.state`.
 */

/** Сегменты пути каталога состояния для join(). */
export function stateDirSegments(env = process.env) {
  const v = env.QG_STATE_DIR;
  if (v && typeof v === 'string') {
    const parts = v.split(/[\\/]+/).filter(Boolean);
    if (parts.length) return parts;
  }
  return ['.claude', '.state'];
}
